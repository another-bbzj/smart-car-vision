#ifndef DRV_CLOCK_H
#define DRV_CLOCK_H

/*
 * ============================================================================
 * 文件名称：Drv_Clock.h
 * ============================================================================
 * 模块功能：1 MHz 自由运行计数器，提供控制周期的真实测量。
 *
 *   外设资源
 *     TIM5（32 位，约 71 分钟回绕）—— 默认时基；
 *     TIM7（16 位，约 65.5 ms 回绕）—— ENCODER_RIGHT_ON_TIM5 = 1 时接替。
 *
 *   运行视角
 *     控制中断开头调 Clock_PeriodUs()，得到“距上一拍”的实际微秒数。
 *     标称 5000 µs；实测值参与 dt 校正、堵转判定和时序故障判定，
 *     所以时基失效会让 Car_TickDt 直接判 CAR_TIMING_FAULT。
 * ============================================================================
 */

#include <stdint.h>

/* ---------------------------------------------------------------------------
 * 外设：TIM5 / TIM7 预分频目标
 * 功能：把定时器输入时钟分频到 1 MHz，使 1 个计数 = 1 µs。
 * 取值：1000000。定时器时钟必须能被它整除，否则 Clock_Init() 返回失败。
 * ------------------------------------------------------------------------- */
#define CLOCK_TICK_HZ            1000000U   /* 控制时基频率，单位 Hz */

/*
 * 函数名称：Clock_Init
 * 函数功能：把控制时基配置成 1 MHz 自由运行计数器并启动。
 * 参数说明：无。
 * 返回参数：1 成功；0 时钟无法整除 1 MHz 或 HAL 初始化失败。
 * 备注信息：失败不代表要停机，但 dt 会变成 0，由任务层判时序故障。
 */
uint8_t Clock_Init(void);

/*
 * 函数名称：Clock_PeriodUs
 * 函数功能：读取当前计数并返回距上一次调用经过的微秒数。
 * 参数说明：无。
 * 返回参数：本拍实际周期，微秒；未初始化时返回 0。
 * 备注信息：每条控制周期必须恰好调用一次。TIM7 方案下按 uint16_t 截断
 *           再相减，5 ms 远小于 65.536 ms 回绕周期。
 */
uint32_t Clock_PeriodUs(void);

#endif
