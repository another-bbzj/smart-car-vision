#ifndef DRV_ENCODER_H
#define DRV_ENCODER_H

/*
 * ============================================================================
 * 文件名称：Drv_Encoder.h
 * ============================================================================
 * 模块功能：左右轮正交编码器测速输入。
 *
 *   外设资源
 *     TIM4 PB6/PB7 -> 左轮编码器 A/B
 *     TIM3 PA6/PA7 -> 右轮编码器 A/B（与板载 W25Q 的 MISO/MOSI 复用）
 *     TIM5 PA0/PA1 -> 右轮编码器（仅 ENCODER_RIGHT_ON_TIM5 = 1 时启用）
 *
 *   运行视角
 *     控制中断每 5 ms 调一次 Encoder_Delta()，得到本拍有符号计数增量：
 *     正值代表车轮向前。计数不清零，用 16 位模差处理回绕，不会丢脉冲。
 * ============================================================================
 */

#include <stdint.h>

/* ---------------------------------------------------------------------------
 * 外设：TIM4 / TIM3（或 TIM5）编码器接口
 * 功能：每输出轴一圈的计数。接线图标注电机轴每圈每相 11 个脉冲，
 *       定时器四倍频，减速比 10:1 -> 11 × 4 × 10 = 440。
 * 取值：440。改轮子/减速箱后必须重新标定，否则转速和里程都错。
 * ------------------------------------------------------------------------- */
#define ENCODER_CPR              (11.0f * 4.0f * 10.0f)  /* 输出轴每圈计数 = 440 */

/* ---------------------------------------------------------------------------
 * 外设：编码器输入滤波（TIMx CCMR1 的 IC1F/IC2F）
 * 功能：压掉电机 PWM、地弹、线缆耦合引入的窄毛刺。0 = 不滤波；
 *       0xF 对应 fDTS/32、N=8，约 3 µs（TIM3/TIM4 时钟 84 MHz）。
 * 取值：0xF。1000 rpm 时计数边沿间隔约 136 µs，远大于 3 µs，不会误滤真计数。
 * ------------------------------------------------------------------------- */
#define ENCODER_IC_FILTER        0xFU   /* 编码器输入滤波档位：0..15 */

/* ---------------------------------------------------------------------------
 * 外设：编码器安装方向
 * 功能：编码器 A/B 接反时计数会反向，闭环会正反馈跑到限幅。这里取反后
 *       保证“车轮向前 -> 计数为正”。
 * 取值：左轮取反、右轮不取反（2026-11-18 实车核对）。
 * 注意：与 MOTOR_*_FORWARD_HIGH 只能改其中一个，同时改会互相抵消。
 * ------------------------------------------------------------------------- */
#define ENCODER_LEFT_INVERT      1      /* 1=左轮计数取反 */
#define ENCODER_RIGHT_INVERT     0      /* 1=右轮计数取反 */

/* ---------------------------------------------------------------------------
 * 外设：右编码器定时器选择（C 方案）
 * 功能：0 = 右编码器留在 TIM3（PA6/PA7，与 W25Q 复用），TIM5 作 1 MHz 时基；
 *       1 = 右编码器改接 TIM5（PA0/PA1），时基自动切到 TIM7。
 * 取值：0（保持现有接线）。改 1 之前必须先把 A/B 两根线物理改接到 PA0/PA1。
 * ------------------------------------------------------------------------- */
#ifndef ENCODER_RIGHT_ON_TIM5
#define ENCODER_RIGHT_ON_TIM5    0
#endif
#if ENCODER_RIGHT_ON_TIM5 != 0 && ENCODER_RIGHT_ON_TIM5 != 1
#error ENCODER_RIGHT_ON_TIM5 must be 0 or 1
#endif

/*
 * 函数名称：Encoder_Init
 * 函数功能：配置两路编码器接口、写入输入滤波、建立计数基准。
 * 参数说明：无。
 * 返回参数：无。
 * 备注信息：必须在 PIT 启动前调用，否则首拍计数增量会包含初始化瞬间的
 *           无效脉冲；同时要求 BOARD_FLASH_CS 已拉高（PA6/PA7 复用）。
 */
void Encoder_Init(void);

/*
 * 函数名称：Encoder_Delta
 * 函数功能：读取指定轮编码器，返回本周期有符号计数增量。
 * 参数说明：wheel —— 0 左轮、1 右轮（越界返回 0）。
 * 返回参数：本周期计数增量，正负号表示转向，已按 ENCODER_*_INVERT 取反。
 * 备注信息：计数器不清零，用 16 位模差处理回绕；前提是相邻两次采样的
 *           真实增量绝对值小于 32768。
 */
int32_t Encoder_Delta(unsigned wheel);

#endif
