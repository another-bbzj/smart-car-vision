#ifndef DRV_MOTOR_H
#define DRV_MOTOR_H

/*
 * ============================================================================
 * 文件名称：Drv_Motor.h
 * ============================================================================
 * 模块功能：左/右轮直流电机的 PWM 与方向引脚驱动。
 *
 *   外设资源
 *     TIM8_CH1 / PC6  -> 左轮 PWM（NEUQ 库 PWM 通道）
 *     PC7             -> 左轮方向
 *     TIM2_CH3 / PA2  -> 右轮 PWM
 *     PA5             -> 右轮方向（与板载 W25Q 的 SCK 复用，必须先拉高 CS）
 *
 *   运行视角
 *     控制中断算出 car.output[]（带符号 PWM 数值）后调用 Motor_Apply()：
 *     正值正转、负值反转；换向时先撤 PWM 一个控制周期再翻转方向引脚，
 *     避免 H 桥上下管直通。
 * ============================================================================
 */

#include <stdint.h>

/* ---------------------------------------------------------------------------
 * 外设：TIM8_CH1(PC6) / TIM2_CH3(PA2) 两路 PWM，PC7 / PA5 两路方向
 * 功能：轮位与引脚绑定。通道 1 为左轮、通道 2 为右轮，改动前必须核对原理图。
 * 取值：硬件固定，不可改。
 * ------------------------------------------------------------------------- */
#define MOTOR_LEFT_PWM           TIM8_CH1_PC6   /* 左轮 PWM 通道 */
#define MOTOR_LEFT_DIR           PC7            /* 左轮方向引脚 */
#define MOTOR_RIGHT_PWM          TIM2_CH3_PA2   /* 右轮 PWM 通道 */
#define MOTOR_RIGHT_DIR          PA5            /* 右轮方向引脚 */

/* ---------------------------------------------------------------------------
 * 外设：方向引脚电平极性
 * 功能：定义“前进”对应的方向引脚电平。实车核对方法：架空车轮给 +60 rpm，
 *       车轮应向前转；反转就改这里的电平，不要改编码器取反（两者同时改会
 *       互相抵消，闭环变成正反馈）。
 * 取值：2026-11-18 实车核对结果——左轮前进高电平；右轮方向引脚相反，
 *       前进为低电平。
 * ------------------------------------------------------------------------- */
#define MOTOR_LEFT_FORWARD_HIGH  1              /* 1=高电平前进；0=低电平前进 */
#define MOTOR_RIGHT_FORWARD_HIGH 0              /* 右轮硬件接线相反，前进为低电平 */

/* ---------------------------------------------------------------------------
 * 外设：TIM8 / TIM2 的 PWM 载波
 * 功能：开关频率。8 kHz 高于人耳可听上限，且远高于电流环带宽，电机噪声小。
 * 取值：8000 Hz。
 * ------------------------------------------------------------------------- */
#define MOTOR_PWM_HZ             8000U          /* PWM 载波频率，单位 Hz */

/*
 * 函数名称：Motor_Init
 * 函数功能：把两轮方向引脚置为“停止”电平，初始化 PWM 通道，占空比 0。
 * 参数说明：无。
 * 返回参数：无。
 * 备注信息：必须在 BOARD_FLASH_CS 拉高之后调用（PA5 与 W25Q SCK 复用）。
 */
void Motor_Init(void);

/*
 * 函数名称：Motor_HoldOff
 * 函数功能：在 PWM 初始化之前，把两路 EN 脚（PC6/PA2）拉低，强制电机不转。
 * 参数说明：无。
 * 返回参数：无。
 * 备注信息：上电后第一件事就调用，防止初始化过程中电机突然转动。
 */
void Motor_HoldOff(void);

/*
 * 函数名称：Motor_Apply
 * 函数功能：把带符号 PWM 数值应用到指定车轮。
 * 参数说明：wheel —— 0 左轮、1 右轮；
 *           pwm   —— 带符号 PWM 数值，正负号表示方向，绝对值表示占空比。
 * 返回参数：无。
 * 备注信息：换向时先撤 PWM、下一拍再翻方向引脚，形成一个控制周期的
 *           换向死区；0 输出只撤 PWM，不改方向。
 */
void Motor_Apply(unsigned wheel, float pwm);

#endif
