#ifndef DRV_KEY_H
#define DRV_KEY_H

/*
 * ============================================================================
 * 文件名称：Drv_Key.h
 * ============================================================================
 * 模块功能：板载四个菜单按键（上 / 下 / 确认 / 返回）的扫描与事件队列。
 *
 *   外设资源：PE10 / PE8 / PE7 / PE9，四个键都是低电平有效、内部上拉。
 *
 *   运行视角
 *     控制中断每 10 ms 调一次 Key_Scan()：消抖后只往队列里“记事件”，
 *     中断保持很短；主循环用 Key_GetEvent() 取事件，菜单逻辑不在中断里跑。
 *     长按上/下键会按 KEY_REPEAT_* 产生连发事件，用于快速翻菜单。
 *
 *   PE10 复用：行驶中按 PE10 是“立即停车”，优先级高于所有菜单操作。
 * ============================================================================
 */

#include <stdint.h>

/* ---------------------------------------------------------------------------
 * 外设：按键 GPIO
 * 功能：引脚绑定与“按下时的电平”。引脚在板子上固定，电平由硬件上拉决定。
 * 取值：PE10 上、PE8 下、PE7 确认、PE9 返回；四个键按下均为低电平。
 * ------------------------------------------------------------------------- */
#define KEY_UP_PIN              PE10          /* 上键：菜单上移 / 数值增大 / 行驶中急停 */
#define KEY_DOWN_PIN            PE8           /* 下键：菜单下移 / 数值减小 */
#define KEY_OK_PIN              PE7           /* 确认键：进入 / 发车 */
#define KEY_BACK_PIN            PE9           /* 返回键：退出 / 取消 */
#define KEY_UP_ACTIVE_LEVEL     GPIO_Low      /* 上键按下时读到的电平 */
#define KEY_DOWN_ACTIVE_LEVEL   GPIO_Low      /* 下键按下时读到的电平 */
#define KEY_OK_ACTIVE_LEVEL     GPIO_Low      /* 确认键按下时读到的电平 */
#define KEY_BACK_ACTIVE_LEVEL   GPIO_Low      /* 返回键按下时读到的电平 */

/* ---------------------------------------------------------------------------
 * 外设：按键时序
 * 功能：扫描周期、消抖次数、长按重复的时间参数。
 * 取值：10 ms 扫描一次；连续 3 次读到同一状态才承认（30 ms 消抖）；
 *       按住 500 ms 产生第一次连发，之后每 100 ms 一次。
 * 注意：扫描周期同时决定“急停响应延迟”，不要随意调大。
 * ------------------------------------------------------------------------- */
#define KEY_SCAN_PERIOD_MS      10U           /* 按键扫描周期，单位毫秒 */
#define KEY_DEBOUNCE_COUNT      3U            /* 消抖确认次数：3 × 10 ms = 30 ms */
#define KEY_REPEAT_DELAY_MS     500U          /* 长按多久后开始连发，单位毫秒 */
#define KEY_REPEAT_PERIOD_MS    100U          /* 连发间隔，单位毫秒 */

/* ---------------------------------------------------------------------------
 * 外设：按键事件队列
 * 功能：环形队列长度，最多缓存 15 个事件（留一个空位区分“满”和“空”）。
 * 取值：16。主循环忙于刷屏时也不会丢按键。
 * ------------------------------------------------------------------------- */
#define KEY_QUEUE_SIZE          16U           /* 事件队列长度，最多存 15 个事件 */

typedef enum {
    KEY_UP = 0,                 /* 上 / 数值增大 */
    KEY_DOWN,                   /* 下 / 数值减小 */
    KEY_OK,                     /* 确认 / 进入 */
    KEY_BACK,                   /* 返回 / 取消 */
    KEY_NUM                     /* 按键个数，不是有效按键 */
} Key_Id_Enum;

typedef enum {
    KEY_EVENT_PRESS  = 1,       /* 按下（消抖后只产生一次） */
    KEY_EVENT_REPEAT = 2,       /* 按住不放的连发（只有上/下键有） */
} Key_Event_Type_Enum;

typedef struct {
    uint8_t id;                 /* 哪个键，取值见 Key_Id_Enum */
    uint8_t type;               /* 什么事件，取值见 Key_Event_Type_Enum */
} Key_Event_Struct;

/*
 * 函数名称：Key_Init
 * 函数功能：把四个按键配置成上拉/下拉输入，清空消抖状态和事件队列。
 * 参数说明：无。
 * 返回参数：无。
 * 备注信息：低电平有效的键配上拉，悬空时读到“松开”。
 */
void Key_Init(void);

/*
 * 函数名称：Key_Scan
 * 函数功能：扫描一次所有按键，消抖后产生按下/连发事件。
 * 参数说明：无。
 * 返回参数：无。
 * 备注信息：必须每 KEY_SCAN_PERIOD_MS 调用一次（在控制中断里分频调用）。
 */
void Key_Scan(void);

/*
 * 函数名称：Key_GetEvent
 * 函数功能：从队列取出一个事件。
 * 参数说明：event —— 取到的事件。
 * 返回参数：1 取到；0 队列空。
 */
uint8_t Key_GetEvent(Key_Event_Struct *event);

/*
 * 函数名称：Key_ClearEvents
 * 函数功能：丢弃尚未处理的事件（例如开机过程中误按的键）。
 * 参数说明：无。
 * 返回参数：无。
 */
void Key_ClearEvents(void);

#endif
