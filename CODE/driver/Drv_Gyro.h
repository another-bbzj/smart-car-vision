#ifndef DRV_GYRO_H
#define DRV_GYRO_H

/*
 * ============================================================================
 * 文件名称：Drv_Gyro.h
 * ============================================================================
 * 模块功能：MPU6050 陀螺仪 Z 轴角速度采集、零偏标定和失效判定。
 *
 *   外设资源：I²C（NEUQ 库硬件 I²C）上的 MPU6050，地址与引脚复用由库管理。
 *
 *   运行视角
 *     陀螺仪是慢速外设，放在主循环里每 10 ms 读一次，不在控制中断里读。
 *     控制中断只取一份快照（Gyro_Fresh / Gyro_RateRad），用于巡线状态机的
 *     航向积分；丢帧超过 GYRO_STALE_MS 就退回“只用轮速差”推算 yaw。
 * ============================================================================
 */

#include <stdint.h>

/* ---------------------------------------------------------------------------
 * 外设：MPU6050（I²C）
 * 功能：采样周期、零偏标定样本数、失效判定与安装方向。
 * 取值说明：
 *   GYRO_POLL_MS          10 ms：与菜单刷新同量级，足够 200 Hz 控制用；
 *   GYRO_BIAS_SAMPLES     100 个样本：静止时取平均作为零偏，约 1 s；
 *   GYRO_STILL_RATE_RAD_S 0.12 rad/s：标定期间超过它说明车在动，重新计数；
 *   GYRO_STALE_MS         40 ms：超过它认为陀螺数据过期，巡线不再信任；
 *   GYRO_SIGN             1.0：车体逆时针为正；若装反改成 -1.0。
 * ------------------------------------------------------------------------- */
#define GYRO_POLL_MS             10U        /* 主循环采样间隔，单位毫秒 */
#define GYRO_BIAS_SAMPLES        100        /* 零偏标定样本个数 */
#define GYRO_STILL_RATE_RAD_S    0.12f      /* 标定期间允许的角速度，rad/s */
#define GYRO_STALE_MS            40U        /* 数据过期门限，单位毫秒 */
#define GYRO_SIGN                1.0f       /* 车体逆时针为正；装反改为 -1.0f */

/*
 * 函数名称：Gyro_Init
 * 函数功能：初始化 MPU6050，记录“是否在位”。
 * 参数说明：无。
 * 返回参数：无。
 * 备注信息：不在位时 Gyro_Present() 返回 0，上层自动退回轮速推算 yaw。
 */
void Gyro_Init(void);

/*
 * 函数名称：Gyro_Poll
 * 函数功能：主循环调用，读一次 Z 轴角速度；前 GYRO_BIAS_SAMPLES 个静止
 *           样本用来求零偏，之后输出的就是去零偏的角速度。
 * 参数说明：chassis_still —— 1 表示整车静止（停车且轮速近似为 0）。
 * 返回参数：无。
 * 备注信息：标定期间车身一动就清零重来；读数失败把数据标记为过期。
 */
void Gyro_Poll(uint8_t chassis_still);

/*
 * 函数名称：Gyro_Present
 * 函数功能：查询上电时 MPU6050 是否初始化成功。
 * 参数说明：无。
 * 返回参数：1 在位；0 不在位。
 */
uint8_t Gyro_Present(void);

/*
 * 函数名称：Gyro_Fresh
 * 函数功能：查询当前陀螺快照是否新鲜（未过期）。
 * 参数说明：无。
 * 返回参数：1 新鲜可用；0 过期或从未成功采样。
 */
uint8_t Gyro_Fresh(void);

/*
 * 函数名称：Gyro_RateRad
 * 函数功能：取最近一次去零偏后的 Z 轴角速度。
 * 参数说明：无。
 * 返回参数：角速度，单位 rad/s，逆时针为正。
 */
float Gyro_RateRad(void);

/*
 * 函数名称：Gyro_Samples
 * 函数功能：取已累计的零偏标定样本数，用于菜单显示“标定进度”。
 * 参数说明：无。
 * 返回参数：0..GYRO_BIAS_SAMPLES。
 */
unsigned Gyro_Samples(void);

/*
 * 函数名称：Gyro_BiasRad
 * 函数功能：取当前零偏估计值，仅用于 LCD 显示与调试。
 * 参数说明：无。
 * 返回参数：零偏，单位 rad/s。
 */
float Gyro_BiasRad(void);

#endif
