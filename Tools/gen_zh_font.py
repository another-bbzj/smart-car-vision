"""Generate 20x20 1-bit Chinese bitmap glyphs (CODE/My_Lcd_FontZh.h) from UI strings.

Scans string literals in CODE/Car_Menu.c and My_Lcd_print(...) calls in
CODE/Car_Hardware.c, renders every unique non-ASCII BMP character into a crisp
20x20 monochrome bitmap using SimHei (black sans-serif, uniform stroke width),
and emits a sorted lookup table for O(log N) binary search on STM32F407.
"""
from __future__ import annotations

import pathlib
import re
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
MENU_SRC = ROOT / "CODE" / "Car_Menu.c"
HW_SRC = ROOT / "CODE" / "Car_Hardware.c"
OUT_HDR = ROOT / "CODE" / "My_Lcd_FontZh.h"

FONT_CANDIDATES = [
    pathlib.Path(r"C:\Windows\Fonts\simhei.ttf"),
    pathlib.Path(r"C:\Windows\Fonts\msyh.ttc"),
    pathlib.Path(r"C:\Windows\Fonts\simsun.ttc"),
]

WIDTH = 20
HEIGHT = 20
STRIDE = (WIDTH + 7) // 8  # 3 bytes per row (24 bits, top 20 bits used)
FONT_SIZE = 19
THRESHOLD = 142


def strip_c_comments(text: str) -> str:
    pattern = re.compile(
        r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'',
        re.DOTALL,
    )
    def repl(m: re.Match[str]) -> str:
        s = m.group(0)
        return s if s[0] in ('"', "'") else ""
    return pattern.sub(repl, text)


def extract_string_literals(text: str) -> list[str]:
    clean = strip_c_comments(text)
    return re.findall(r'"((?:\\.|[^"\\])*)"', clean)


def collect_chars() -> list[str]:
    chars: set[str] = set()
    for lit in extract_string_literals(MENU_SRC.read_text(encoding="utf-8")):
        for ch in lit:
            if ord(ch) > 127:
                chars.add(ch)
    hw_clean = strip_c_comments(HW_SRC.read_text(encoding="utf-8"))
    for call in re.findall(r'My_Lcd_print\s*\([^;]*\)', hw_clean):
        for lit in re.findall(r'"((?:\\.|[^"\\])*)"', call):
            for ch in lit:
                if ord(ch) > 127:
                    chars.add(ch)
    for ch in chars:
        if ord(ch) > 0xFFFF:
            raise ValueError(f"Non-BMP character U+{ord(ch):X} not supported: {ch!r}")
    return sorted(chars, key=ord)


def load_font() -> ImageFont.FreeTypeFont:
    for path in FONT_CANDIDATES:
        if path.exists():
            return ImageFont.truetype(str(path), FONT_SIZE)
    raise FileNotFoundError("No Chinese TrueType font found in C:\\Windows\\Fonts")


def render_glyph(font: ImageFont.FreeTypeFont, ch: str) -> bytes:
    # Render onto oversized canvas, crop tight inked bbox, center inside 20x20.
    canvas = Image.new("L", (40, 40), 0)
    draw = ImageDraw.Draw(canvas)
    draw.text((10, 10), ch, fill=255, font=font)
    bbox = canvas.getbbox()
    out = Image.new("L", (WIDTH, HEIGHT), 0)
    if bbox is not None:
        cropped = canvas.crop(bbox)
        cw, ch_h = cropped.size
        if cw > WIDTH or ch_h > HEIGHT:
            scale = min(WIDTH / cw, HEIGHT / ch_h)
            cw = max(1, int(round(cw * scale)))
            ch_h = max(1, int(round(ch_h * scale)))
            cropped = cropped.resize((cw, ch_h), Image.Resampling.LANCZOS)
        ox = (WIDTH - cw) // 2
        oy = (HEIGHT - ch_h) // 2
        out.paste(cropped, (ox, oy))
    px = out.load()
    rows = bytearray()
    for y in range(HEIGHT):
        row_bytes = [0] * STRIDE
        for x in range(WIDTH):
            if px[x, y] >= THRESHOLD:
                row_bytes[x >> 3] |= 0x80 >> (x & 7)
        rows.extend(row_bytes)
    assert len(rows) == HEIGHT * STRIDE
    return bytes(rows)


def preview_glyph(ch: str, data: bytes) -> str:
    lines = [f"=== {ch} (U+{ord(ch):04X}) ==="]
    for y in range(HEIGHT):
        row = data[y * STRIDE : (y + 1) * STRIDE]
        bits = "".join("#" if (row[x >> 3] & (0x80 >> (x & 7))) else "." for x in range(WIDTH))
        lines.append(bits)
    return "\n".join(lines)


def main() -> int:
    chars = collect_chars()
    if not chars:
        raise RuntimeError("No Chinese characters found to generate")
    font = load_font()
    entries: list[tuple[str, bytes]] = [(ch, render_glyph(font, ch)) for ch in chars]

    lines: list[str] = [
        "/* Auto-generated by Tools/gen_zh_font.py - DO NOT EDIT BY HAND. */",
        "#ifndef _MY_LCD_FONT_ZH_H_",
        "#define _MY_LCD_FONT_ZH_H_",
        "",
        "#include <stdint.h>",
        "",
        f"#define MY_LCD_ZH_WIDTH   {WIDTH}U",
        f"#define MY_LCD_ZH_HEIGHT  {HEIGHT}U",
        f"#define MY_LCD_ZH_STRIDE  {STRIDE}U",
        f"#define MY_LCD_ZH_BYTES   {HEIGHT * STRIDE}U",
        "",
        "typedef struct {",
        "    uint16_t unicode;",
        "    uint8_t  bitmap[MY_LCD_ZH_BYTES];",
        "} MyLcdZhGlyph;",
        "",
        "static const MyLcdZhGlyph s_my_lcd_zh_font[] = {",
    ]
    for ch, bmp in entries:
        hex_vals = ", ".join(f"0x{b:02X}" for b in bmp)
        lines.append(f"    /* {ch} U+{ord(ch):04X} */")
        lines.append(f"    {{ 0x{ord(ch):04X}U, {{ {hex_vals} }} }},")
    lines.extend([
        "};",
        "",
        "#define MY_LCD_ZH_COUNT ((unsigned)(sizeof(s_my_lcd_zh_font) / sizeof(s_my_lcd_zh_font[0])))",
        "",
        "#endif",
        "",
    ])
    OUT_HDR.write_text("\n".join(lines), encoding="utf-8")
    total_bytes = len(entries) * (2 + HEIGHT * STRIDE)
    print(f"Generated {OUT_HDR.relative_to(ROOT)}: {len(entries)} glyphs (~{total_bytes} bytes)")
    if "--preview" in sys.argv:
        sample = [e for e in entries if e[0] in ("智", "赛", "视", "速")][:4]
        for ch, bmp in sample:
            print(preview_glyph(ch, bmp))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
